const { test } = require('node:test');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const sharp = require('sharp');
const { fixture } = require('../helpers/integration');
const clone = a => {
  const b = structuredClone(a);
  delete b.id; delete b.content_revision;
  b.slug = 'test-' + randomUUID(); b.variant_key = 'test-' + randomUUID();
  for (const s of b.steps) delete s.id;
  b.content_checked = true;
  return b;
};
test('existing clients retain auth, CRUD, publication, media and snapshot behavior on PostgreSQL', async t => {
  const f = await fixture(t), { request: req } = f;
  let created, image, template;
  const write = (url, body, method = 'POST') => req(url, { method, body, admin: true });
  await t.test('public seed is complete and excludes private fields; v1/v2 have separate ETags', async () => {
    const list = await req('/articles'); assert.equal(list.status, 200);
    assert.equal(list.data.items.length, f.snapshot.articles.length);
    assert.equal(Object.hasOwn(list.data.items[0], 'content_checked'), false);
    template = (await req('/articles/' + list.data.items.find(a => a.age_group === 'ALL').id)).data;
    const v1 = await req('/offline-snapshot?region_code=VN-DN'); assert.equal(v1.status, 200);
    assert.deepEqual(v1.data.facilities, []); assert.equal(v1.data.schema_version, 1);
    const v2 = await req('/offline-snapshot?schema_version=2', { headers: { 'If-None-Match': v1.headers.get('etag') } });
    assert.equal(v2.status, 200); assert.equal(v2.data.schema_version, 2);
    assert.equal(Object.hasOwn(v2.data, 'region_code'), false); assert.equal(Object.hasOwn(v2.data, 'facilities'), false);
    assert.deepEqual(v1.data.articles, v2.data.articles);
    assert.notEqual(v1.headers.get('etag'), v2.headers.get('etag'));
    assert.equal(v2.headers.get('etag'), '"' + v2.data.data_version + '"');
    const cached = await req('/offline-snapshot?schema_version=2&region_code=VN-DN', { headers: { 'If-None-Match': v2.headers.get('etag') } });
    assert.equal(cached.status, 304); assert.equal(cached.json, null);
    assert.equal((await req('/offline-snapshot')).status, 400);
    assert.equal((await req('/offline-snapshot?region_code=OTHER')).status, 400);
    assert.equal((await req('/offline-snapshot?schema_version=3')).status, 400);
    assert.equal((await req('/facilities')).status, 404);
  });
  await t.test('admin requires session and CSRF; login rotates session and preserves bcrypt credentials', async () => {
    assert.equal((await req('/admin/articles')).status, 401);
    assert.equal((await req('/admin/auth/login', { method: 'POST', body: {} })).status, 403);
    const before = await f.refresh();
    const login = await f.login(); assert.equal(login.data.role, 'ADMIN');
    assert.match(login.headers.get('set-cookie'), /HttpOnly/);
    assert.notEqual(before.headers.get('set-cookie'), login.headers.get('set-cookie'));
    assert.equal((await req('/admin/auth/me', { admin: true })).status, 200);
    const stale = await req('/admin/categories', { method: 'POST', admin: true, body: {}, headers: { 'X-CSRF-TOKEN': before.data.token } });
    assert.equal(stale.status, 403); assert.equal(stale.error.code, 'CSRF_INVALID');
    const denied = await req('/admin/categories', { method: 'POST', admin: true, body: {}, token: false }); assert.equal(denied.status, 403);
    assert.equal((await req('/admin/articles?page=0', { admin: true })).status, 400);
    const origin = await req('/categories', { headers: { Origin: f.config.adminOrigin } });
    assert.equal(origin.headers.get('access-control-allow-origin'), f.config.adminOrigin);
    assert.equal((await req('/admin/facilities', { admin: true })).status, 404);
  });
  await t.test('media is decoded and private until attached to a public article', async () => {
    const data = await sharp({ create: { width: 20, height: 12, channels: 3, background: '#abc' } }).png().toBuffer();
    const form = () => { const b = new FormData(); b.append('file', new Blob([data], { type: 'image/png' }), 'photo.png'); return b; };
    assert.equal((await req('/admin/media', { method: 'POST', admin: true, token: false, body: form() })).status, 403);
    const response = await write('/admin/media', form()); assert.equal(response.status, 201);
    image = response.data;
    assert.equal(image.width, 20); assert.equal(image.height, 12);
    assert.equal((await req(image.url.replace('/api/v1', ''))).status, 404);
    assert.equal((await req(image.url.replace('/api/v1', ''), { admin: true })).status, 200);
    const bad = new FormData(); bad.append('file', new Blob(['<svg/>'], { type: 'image/png' }), 'bad.png');
    assert.equal((await write('/admin/media', bad)).status, 400);
  });
  await t.test('nested save keeps duplicate references; invalid nested writes roll back completely', async () => {
    const b = clone(template);
    b.references.push({ ...b.references[0], note: 'second reference to same source' });
    b.steps[0].images = [{ media_id: image.id, url: 'https://untrusted.invalid/', alt_text: 'Test image', caption: '' }];
    b.steps[0].image_layout = 'grid';
    const r = await write('/admin/articles', b); assert.equal(r.status, 201, JSON.stringify(r.error));
    created = r.data;
    assert.equal(created.status, 'DRAFT'); assert.equal(created.content_revision, 1);
    assert.equal(created.references.length, b.references.length);
    assert.equal(created.steps[0].images[0].url, image.url);
    assert.equal((await req('/articles/' + created.id)).status, 404);
    const invalid = { ...created, expected_revision: 1, title: 'must roll back', steps: [{ ...created.steps[0], position: 2 }] };
    assert.equal((await write('/admin/articles/' + created.id, invalid, 'PUT')).status, 400);
    const after = await req('/admin/articles/' + created.id, { admin: true });
    assert.equal(after.data.title, created.title); assert.equal(after.data.content_revision, 1);
    assert.deepEqual(after.data.steps, created.steps);
    const unused = { ...created, expected_revision: 1, steps: [{ ...created.steps[0], images: [{ media_id: randomUUID(), alt_text: 'missing' }] }] };
    assert.equal((await write('/admin/articles/' + created.id, unused, 'PUT')).status, 400);
    assert.equal((await req('/admin/articles/' + created.id, { admin: true })).data.content_revision, 1);
  });
  await t.test('publish and source/category guards enforce prior rules and update snapshots', async () => {
    const before = await req('/offline-snapshot?schema_version=2');
    const published = await write(`/admin/articles/${created.id}/publish`, { expected_revision: 1 });
    assert.equal(published.status, 200, JSON.stringify(published.error)); created = published.data;
    assert.equal((await req('/articles/' + created.id)).status, 200);
    assert.equal((await req(image.url.replace('/api/v1', ''))).status, 200);
    assert.notEqual((await req('/offline-snapshot?schema_version=2')).headers.get('etag'), before.headers.get('etag'));
    const category = (await req('/admin/categories/' + created.category_id, { admin: true })).data;
    assert.equal((await write('/admin/categories/' + category.id, { ...category, is_active: false }, 'PUT')).status, 409);
    assert.equal((await write('/admin/categories/' + category.id, undefined, 'DELETE')).status, 409);
    assert.equal((await write('/admin/categories/' + category.id, { ...category, code: 'FA99' }, 'PUT')).status, 400);
    const sourceId = created.references[0].source_id;
    const source = (await req('/admin/sources/' + sourceId, { admin: true })).data;
    assert.equal((await write('/admin/sources/' + sourceId, { ...source, is_active: false }, 'PUT')).status, 409);
    assert.equal((await write('/admin/sources/' + sourceId, undefined, 'DELETE')).status, 409);
    if (source.media_type === 'PDF') assert.equal((await write('/admin/sources/' + sourceId, { ...source, page_count: 1 }, 'PUT')).status, 409);
    const rights = await write('/admin/sources/' + sourceId, { ...source, rights_note: 'Test rights note' }, 'PUT');
    assert.equal(rights.data.revision, source.revision);
    const metadata = await write('/admin/sources/' + sourceId, { ...rights.data, title: source.title + ' test' }, 'PUT');
    assert.equal(metadata.data.revision, source.revision + 1);
  });
  await t.test('simultaneous updates allow only one revision; public edits withdraw media and clear checked state', async () => {
    const body = { ...created, expected_revision: 1, content_checked: true };
    const results = await Promise.all([write('/admin/articles/' + created.id, { ...body, title: 'first' }, 'PUT'), write('/admin/articles/' + created.id, { ...body, title: 'second' }, 'PUT')]);
    assert.deepEqual(results.map(r => r.status).sort(), [200, 409]);
    created = results.find(r => r.status === 200).data;
    assert.equal(created.content_revision, 2); assert.equal(created.status, 'DRAFT'); assert.equal(created.content_checked, false); assert.equal(created.checked_at, null);
    assert.equal((await req('/articles/' + created.id)).status, 404);
    assert.equal((await req(image.url.replace('/api/v1', ''))).status, 404);
    const rejected = await write(`/admin/articles/${created.id}/publish`, { expected_revision: 2 });
    assert.equal(rejected.status, 422); assert.equal(rejected.error.code, 'CONTENT_NOT_READY');
    const saved = await write('/admin/articles/' + created.id, { ...created, expected_revision: 2, content_checked: true }, 'PUT');
    assert.equal(saved.status, 200); created = saved.data;
    assert.equal((await write(`/admin/articles/${created.id}/publish`, { expected_revision: 3 })).status, 200);
    assert.equal((await write(`/admin/articles/${created.id}/unpublish`, { expected_revision: 2 })).status, 409);
    assert.equal((await write(`/admin/articles/${created.id}/unpublish`, { expected_revision: 3 })).status, 200);
    assert.equal((await req(image.url.replace('/api/v1', ''))).status, 404);
    assert.equal((await req(image.url.replace('/api/v1', ''), { admin: true })).status, 200);
    assert.equal((await write('/admin/articles/' + created.id, undefined, 'DELETE')).status, 204);
  });
  await t.test('search count matches literal wildcard filter, age filters are explicit, and logout invalidates session', async () => {
    const a = await req('/admin/articles?q=%25', { admin: true });
    assert.equal(a.data.total, a.data.items.length);
    const adult = await req('/articles?age_group=ADULT');
    assert.equal(adult.data.items.every(a => ['ADULT', 'ALL'].includes(a.age_group)), true);
    assert.equal((await req('/articles?age_group=INFANT')).status, 400);
    assert.equal((await req('/articles/not-a-uuid')).status, 400);
    assert.equal((await write('/admin/auth/logout', {})).status, 204);
    assert.equal((await req('/admin/auth/me', { admin: true })).status, 401);
  });
});
